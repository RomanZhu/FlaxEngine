int32 AssetsCache::Size() const
{
    ASSETS_CACHE_LOCK();
#if USE_EDITOR
    const int32 result = _registry.Count();
#else
    const int32 result = _runtimeCatalog.GetEntries().Count();
#endif
    return result;
}

