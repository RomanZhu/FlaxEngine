void AssetsCache::Init()
{
    PROFILE_CPU();
#if !USE_EDITOR
    _path = Globals::ProjectContentFolder / TEXT("RuntimeAssetCatalog.bin");
    LOG(Info, "Loading runtime asset catalog {0}...", _path);
    AssetPipelineDiagnostic diagnostic;
    if (RuntimeAssetCatalog::Load(_path, _runtimeCatalog, diagnostic))
    {
        LOG(Error, "Cannot load runtime asset catalog: {0}", diagnostic.Message);
        return;
    }

    Stopwatch runtimeStopwatch;
    int32 rejectedCount = 0;
    for (const RuntimeAssetCatalogEntry& catalogEntry : _runtimeCatalog.GetEntries())
    {
        AssetInfo info;
        MakeRuntimeAssetInfo(catalogEntry, info);
        if (!FileSystem::FileExists(info.Path))
            rejectedCount++;
    }
    runtimeStopwatch.Stop();
    if (rejectedCount != 0)
        LOG(Error, "Runtime asset catalog references {0} missing package objects.", rejectedCount);
    LOG(Info, "Runtime asset catalog loaded {0} objects and {1} path aliases in {2}ms ({3} rejected)",
        _runtimeCatalog.GetEntries().Count(), _runtimeCatalog.GetAliases().Count(), runtimeStopwatch.GetMilliseconds(), rejectedCount);
#else

    Entry e;
    int32 count;
    Stopwatch stopwatch;
    _path = Globals::ProjectCacheFolder / TEXT("AssetsCache.dat");
    LOG(Info, "Loading Asset Cache {0}...", _path);

    // Check if assets registry exists
    if (!FileSystem::FileExists(_path))
    {
        _isDirty = true;
        LOG(Info, "Asset cache is not present; starting with an empty compatibility registry.");
        return;
    }

    // Open file
    FileReadStream* stream = FileReadStream::Open(_path);
    DeleteMe<FileReadStream> deleteStream(stream);

    // Load version
    int32 version;
    stream->Read(version);
    if (version != FLAXENGINE_VERSION_BUILD)
    {
        LOG(Warning, "Corrupted or not supported Asset Cache file. Version: {0}", version);
        return;
    }

    // Load paths
    String enginePath, projectPath;
    stream->Read(enginePath, -410);
    stream->Read(projectPath, -410);

    // Flags
    AssetsCacheFlags flags;
    stream->Read((int32&)flags);

    // Check if other workspace instance used this cache
    if (EnumHasNoneFlags(flags, AssetsCacheFlags::RelativePaths) && enginePath != Globals::StartupFolder)
    {
        LOG(Warning, "Assets cache generated by the different {1} installation in \'{0}\'", enginePath, TEXT("engine"));
        return;
    }
    if (EnumHasNoneFlags(flags, AssetsCacheFlags::RelativePaths) && projectPath != Globals::ProjectFolder)
    {
        LOG(Warning, "Assets cache generated by the different {1} installation in \'{0}\'", projectPath, TEXT("project"));
        return;
    }

    ASSETS_CACHE_LOCK();
    _isDirty = false;

    // Load elements count
    stream->Read(count);
    _registry.Clear();
    _registry.EnsureCapacity(count);

    // Load data
    int32 rejectedCount = 0;
    for (int32 i = 0; i < count; i++)
    {
        stream->Read(e.Info.ID);
        e.Info.ObjectID = AssetObjectId::Main(AssetGuid(e.Info.ID));
        e.Info.Revision = 0;
        stream->Read(e.Info.TypeName, i - 13);
        stream->Read(e.Info.Path, i);
#if ENABLE_ASSETS_DISCOVERY
        stream->Read(e.FileModified);
#else
        DateTime tmp1;
        stream->Read(tmp1);
#endif

        if (EnumHasAnyFlags(flags, AssetsCacheFlags::RelativePaths) && e.Info.Path.HasChars())
        {
            // Convert to absolute path
            e.Info.Path = Globals::StartupFolder / e.Info.Path;
        }
        FileSystem::NormalizePath(e.Info.Path);

        // Use only valid entries
        if (IsEntryValid(e) != EntryValidation::Invalid)
            _registry.Add(e.Info.ID, e);
        else
            rejectedCount++;
    }

    // Paths mapping
    stream->ReadInt32(&count);
    _pathsMapping.Clear();
    _pathsMapping.EnsureCapacity(count);
    for (int32 i = 0; i < count; i++)
    {
        Guid id;
        stream->Read(id);
        String mappedPath;
        stream->Read(mappedPath, i + 73);

        if (EnumHasAnyFlags(flags, AssetsCacheFlags::RelativePaths) && mappedPath.HasChars())
        {
            // Convert to absolute path
            mappedPath = Globals::StartupFolder / mappedPath;
        }
        FileSystem::NormalizePath(mappedPath);

        _pathsMapping.Add(mappedPath, id);
    }

    // Check errors
    const bool hasError = stream->HasError();
    deleteStream.Delete();
    if (hasError)
    {
        _isDirty = true;
        _registry.Clear();
        LOG(Warning, "Asset Cache file has an error. Removing it.");
        if (FileSystem::DeleteFile(_path))
        {
            LOG(Error, "Cannot delete registry file after reading error.");
        }
    }

    stopwatch.Stop();
    LOG(Info, "Asset Cache loaded {0} entries in {1}ms ({2} rejected)", _registry.Count(), stopwatch.GetMilliseconds(), rejectedCount);
#endif
}

bool AssetsCache::Save()
{
    // Registry can be saved only in editor
#if USE_EDITOR

    // Check if registry hasn't been edited
    if (!_isDirty && FileSystem::FileExists(_path))
        return false;

    ASSETS_CACHE_LOCK();

    if (Save(_path, _registry, _pathsMapping))
        return true;

    _isDirty = false;

#endif

    return false;
}

bool AssetsCache::Save(const StringView& path, const Registry& entries, const PathsMapping& pathsMapping, const AssetsCacheFlags flags)
{
    PROFILE_CPU();

    LOG(Info, "Saving assets cache to \'{0}\', entries: {1}", path, entries.Count());

    // Open file
    auto stream = FileWriteStream::Open(path);
    if (stream == nullptr)
        return true;

    // Version
    stream->Write((int32)FLAXENGINE_VERSION_BUILD);

    // Paths
    stream->Write(Globals::StartupFolder, -410);
    stream->Write(Globals::ProjectFolder, -410);

    // Flags
    stream->Write((int32)flags);

    // Items count
    stream->Write(entries.Count());

    // Data
    int32 index = 0;
    for (auto i = entries.Begin(); i.IsNotEnd(); ++i)
    {
        auto& e = i->Value;
        stream->Write(e.Info.ID);
        stream->Write(e.Info.TypeName, index - 13);
        stream->Write(e.Info.Path, index);
#if ENABLE_ASSETS_DISCOVERY
        stream->Write(e.FileModified);
#else
        stream->Write((int64)0);
#endif
        index++;
    }

    // Paths mapping
    index = 0;
    stream->WriteInt32(pathsMapping.Count());
    for (auto i = pathsMapping.Begin(); i.IsNotEnd(); ++i)
    {
        stream->Write(i->Value);
        stream->Write(i->Key, index + 73);
        index++;
    }

    // Cleanup
    stream->Flush();
    Delete(stream);

    return false;
}

StringView AssetsCache::GetEditorAssetPath(const Guid& id) const
{
    ASSETS_CACHE_LOCK();
#if USE_EDITOR
    auto e = _registry.TryGet(id);
    return e ? e->Info.Path : String::Empty;
#else
    // Runtime source paths are intentionally absent. Use catalog path aliases for lookup instead.
    return String::Empty;
#endif
}

bool AssetsCache::FindAsset(const StringView& path, AssetInfo& info)
{
    PROFILE_CPU();
#if !USE_EDITOR
    String aliasPath = NormalizeAssetPath(path);
    const String startupPath = NormalizeAssetPath(Globals::StartupFolder);
    if (aliasPath.StartsWith(startupPath) && aliasPath.Length() > startupPath.Length() &&
        aliasPath[startupPath.Length()] == '/')
        aliasPath = aliasPath.Right(aliasPath.Length() - startupPath.Length() - 1);
    ContentHash aliasHash;
    AssetObjectId object;
    return !RuntimeAssetCatalog::HashPathAlias(aliasPath, aliasHash) &&
        _runtimeCatalog.TryGetByPathHash(aliasHash, object) && FindAsset(object, info);
#else
    bool result = false;
    const String formattedPath = NormalizeAssetPath(path);
    ASSETS_CACHE_LOCK();

    // Check if asset has direct mapping to id (used for some cooked assets)
    Guid id;
    if (_pathsMapping.TryGet(formattedPath, id))
    {
        return FindAsset(id, info);
    }
    // Find asset in registry
    for (auto i = _registry.Begin(); i.IsNotEnd(); ++i)
    {
        auto& e = i->Value;
        if (e.Info.Path == formattedPath)
        {
            const auto validation = IsEntryValid(e);
            if (validation == EntryValidation::Invalid)
            {
                LOG(Warning, "Missing file from registry: \'{0}\':{1}:{2}", e.Info.Path, e.Info.ID, e.Info.TypeName);
                _registry.Remove(i);
            }
            else
            {
#if ENABLE_ASSETS_DISCOVERY
                if (validation == EntryValidation::Inaccessible && !e.WarnedInaccessible)
                {
                    e.WarnedInaccessible = true;
                    LOG(Warning, "Asset file locked, keeping cached entry: \'{0}\':{1}:{2}", e.Info.Path, e.Info.ID, e.Info.TypeName);
                }
#endif

                // Found valid or inaccessible but return cached info either way
                result = true;
                info = e.Info;
            }

            break;
        }
    }

    return result;
#endif
}

bool AssetsCache::FindAsset(const Guid& id, AssetInfo& info)
{
    PROFILE_CPU();
#if !USE_EDITOR
    if (!id.IsValid())
        return false;
    for (const RuntimeAssetCatalogEntry& entry : _runtimeCatalog.GetEntries())
    {
        if (entry.Object.ToRuntimeObjectGuid() == id)
            return FindAsset(entry.Object, info);
    }
    return false;
#else
    bool result = false;
    ASSETS_CACHE_LOCK();
    auto e = _registry.TryGet(id);
    if (e != nullptr)
    {
        const auto validation = IsEntryValid(*e);
        if (validation == EntryValidation::Invalid)
        {
            LOG(Warning, "Missing file from registry: \'{0}\':{1}:{2}", e->Info.Path, e->Info.ID, e->Info.TypeName);
            _registry.Remove(id);
        }
        else
        {
#if ENABLE_ASSETS_DISCOVERY
            if (validation == EntryValidation::Inaccessible && !e->WarnedInaccessible)
            {
                e->WarnedInaccessible = true;
                LOG(Warning, "Asset file locked, keeping cached entry: \'{0}\':{1}:{2}", e->Info.Path, e->Info.ID, e->Info.TypeName);
            }
#endif

            // Found
            result = true;
            info = e->Info;
        }
    }
    return result;
#endif
}

bool AssetsCache::FindAsset(const AssetObjectId& id, AssetInfo& info)
{
    PROFILE_CPU();
    if (!id.IsValid())
        return false;
#if !USE_EDITOR
    RuntimeAssetCatalogEntry entry;
    if (!_runtimeCatalog.TryGet(id, entry))
        return false;
    MakeRuntimeAssetInfo(entry, info);
    return FileSystem::FileExists(info.Path);
#else
    if (!FindAsset(id.ToRuntimeObjectGuid(), info))
        return false;
    if (!info.ObjectID.IsValid())
        info.ObjectID = AssetObjectId::Main(AssetGuid(info.ID));
    return info.ObjectID == id;
#endif
}

void AssetsCache::GetAll(Array<Guid>& result) const
{
    PROFILE_CPU();
    ASSETS_CACHE_LOCK();
#if USE_EDITOR
    _registry.GetKeys(result);
#else
    result.EnsureCapacity(result.Count() + _runtimeCatalog.GetEntries().Count());
    for (const RuntimeAssetCatalogEntry& entry : _runtimeCatalog.GetEntries())
        result.Add(entry.Object.ToRuntimeObjectGuid());
#endif
}

void AssetsCache::GetAllByTypeName(const StringView& typeName, Array<Guid>& result) const
{
    PROFILE_CPU();
    ASSETS_CACHE_LOCK();
#if USE_EDITOR
    for (auto i = _registry.Begin(); i.IsNotEnd(); ++i)
    {
        if (i->Value.Info.TypeName == typeName)
            result.Add(i->Key);
    }
#else
    for (const RuntimeAssetCatalogEntry& entry : _runtimeCatalog.GetEntries())
    {
        if (String(entry.TypeName) == typeName)
            result.Add(entry.Object.ToRuntimeObjectGuid());
    }
#endif
}

